"""Refresh GoogleIP.list using the Google Workspace default-domain IP ranges."""

import ipaddress
import json
from pathlib import Path
from tempfile import NamedTemporaryFile
from urllib.request import urlopen


def fetch_ranges(filename):
    with urlopen(f"https://www.gstatic.com/ipranges/{filename}", timeout=30) as response:
        data = json.load(response)
    return data["prefixes"]


def service_ranges(google, cloud):
    for key in ("ipv4Prefix", "ipv6Prefix"):
        service = list(ipaddress.collapse_addresses(
            ipaddress.ip_network(row[key]) for row in google if key in row
        ))
        cloud_networks = list(ipaddress.collapse_addresses(
            ipaddress.ip_network(row[key]) for row in cloud if key in row
        ))
        if not service or not cloud_networks:
            raise ValueError(f"Missing {key} ranges from a Google feed")
        for cloud_network in cloud_networks:
            remaining = []
            for network in service:
                if not network.overlaps(cloud_network):
                    remaining.append(network)
                elif not network.subnet_of(cloud_network):
                    remaining.extend(network.address_exclude(cloud_network))
            service = remaining
        if not service:
            raise ValueError(f"No Google service ranges left for {key}")
        yield from sorted(service)


def main():
    google = fetch_ranges("goog.json")
    cloud = fetch_ranges("cloud.json")
    rules = [
        "# Generated by update_google_ips.py from goog.json minus cloud.json.",
        "# Source: https://knowledge.workspace.google.com/admin/security/obtain-google-ip-address-ranges",
    ]
    for network in service_ranges(google, cloud):
        kind = "IP-CIDR" if network.version == 4 else "IP-CIDR6"
        rules.append(f"{kind},{network},no-resolve")

    output = Path(__file__).with_name("GoogleIP.list")
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=output.parent, delete=False) as staging:
        staged_path = Path(staging.name)
        try:
            staging.write("\n".join(rules) + "\n")
            staging.close()
            staged_path.chmod(0o644)
            staged_path.replace(output)
        finally:
            staged_path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
